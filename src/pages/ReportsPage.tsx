import { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import PageHeader from '../components/layout/PageHeader';
import Card from '../components/ui/Card';
import Badge from '../components/ui/Badge';
import Button from '../components/ui/Button';
import * as reportService from '../services';
import type { Report } from '../types';

export function ReportsPage() {
  const navigate = useNavigate();

  const [reports, setReports] = useState<Report[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let mounted = true;

    const fetchReports = async () => {
      try {
        setLoading(true);

        const data = await reportService.getReports();

        if (mounted) {
          setReports(data || []);
        }
      } catch (error) {
        console.error('Failed to load reports:', error);

        if (mounted) {
          setReports([]);
        }
      } finally {
        if (mounted) {
          setLoading(false);
        }
      }
    };

    fetchReports();

    return () => {
      mounted = false;
    };
  }, []);

  const handleDownload = (report: Report) => {
    /*
     * Prototype download.
     * Creates a simple text report locally.
     */
    const reportText = `
BHUMI-X
Government Land Intelligence & Decision Engine

REPORT ID: ${report.report_id}
REGION: ${report.region}
FACILITY: ${report.facility}
DATE: ${report.date}
STATUS: ${report.status}
TOP PARCEL: ${report.top_parcel}
SUITABILITY SCORE: ${report.top_score}/100

Generated by BHUMI-X prototype.
`;

    const blob = new Blob([reportText], {
      type: 'text/plain',
    });

    const url = URL.createObjectURL(blob);

    const link = document.createElement('a');
    link.href = url;
    link.download = `${report.report_id}.txt`;

    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    URL.revokeObjectURL(url);
  };

  const handleView = (report: Report) => {
    /*
     * Open the results page for the report.
     * The generated report currently corresponds to A102.
     */
    if (report.top_parcel) {
      navigate(`/parcel/${report.top_parcel}`);
    } else {
      navigate('/results');
    }
  };

  return (
    <div className="max-w-6xl mx-auto py-6 space-y-6">
      <PageHeader
        title="Reports"
        description="View and manage planning reports."
      />

      <Card className="overflow-hidden">
        {loading ? (
          <div className="p-8 text-center text-gray-500">
            Loading reports...
          </div>
        ) : reports.length === 0 ? (
          <div className="p-8 text-center text-gray-500">
            No reports found.
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="min-w-full divide-y divide-gray-200">
              <thead className="bg-gray-50">
                <tr>
                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Report ID
                  </th>

                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Region
                  </th>

                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Facility
                  </th>

                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Date
                  </th>

                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Status
                  </th>

                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Top Parcel
                  </th>

                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Score
                  </th>

                  <th className="px-6 py-3 text-right text-xs font-medium text-gray-500 uppercase tracking-wider">
                    Actions
                  </th>
                </tr>
              </thead>

              <tbody className="bg-white divide-y divide-gray-200">
                {reports.map((report) => (
                  <tr
                    key={report.report_id}
                    className="hover:bg-gray-50"
                  >
                    <td className="px-6 py-4 whitespace-nowrap text-sm font-medium text-gray-900">
                      {report.report_id}
                    </td>

                    <td className="px-6 py-4 whitespace-nowrap text-sm text-gray-500 capitalize">
                      {report.region}
                    </td>

                    <td className="px-6 py-4 whitespace-nowrap text-sm text-gray-500 capitalize">
                      {report.facility.replace('_', ' ')}
                    </td>

                    <td className="px-6 py-4 whitespace-nowrap text-sm text-gray-500">
                      {report.date}
                    </td>

                    <td className="px-6 py-4 whitespace-nowrap">
                      <Badge
                        variant={
                          report.status === 'completed'
                            ? 'success'
                            : 'default'
                        }
                      >
                        {report.status}
                      </Badge>
                    </td>

                    <td className="px-6 py-4 whitespace-nowrap text-sm text-blue-600 font-medium">
                      {report.top_parcel}
                    </td>

                    <td className="px-6 py-4 whitespace-nowrap text-sm font-semibold text-gray-900">
                      {report.top_score}
                    </td>

                    <td className="px-6 py-4 whitespace-nowrap text-right text-sm font-medium space-x-3">
                      <Button
                        variant="secondary"
                        size="sm"
                        onClick={() => handleView(report)}
                      >
                        View
                      </Button>

                      <Button
                        variant="primary"
                        size="sm"
                        onClick={() => handleDownload(report)}
                      >
                        Download
                      </Button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </div>
  );
}